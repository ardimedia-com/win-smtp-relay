namespace WinSmtpRelay.Core.Models;

public class QueuedMessage : ITenantOwned
{
    public long Id { get; set; }
    public int TenantId { get; set; } = TenantDefaults.DefaultTenantId;
    public required string MessageId { get; set; }

    /// <summary>The envelope sender (MAIL FROM). Empty for a null return path (<c>MAIL FROM:&lt;&gt;</c>, a bounce/DSN).</summary>
    public required string Sender { get; set; }
    public required string Recipients { get; set; }
    public required byte[] RawMessage { get; set; }
    public int SizeBytes { get; set; }
    public MessageStatus Status { get; set; } = MessageStatus.Queued;
    public int RetryCount { get; set; }
    public string? LastError { get; set; }
    public DateTimeOffset CreatedUtc { get; set; } = DateTimeOffset.UtcNow;

    /// <summary>
    /// When the message is next eligible for delivery. Always set (a new message is due immediately), so the queue
    /// pick is a plain indexed range filter on (<see cref="Status"/>, <see cref="NextRetryUtc"/>).
    /// </summary>
    public DateTimeOffset NextRetryUtc { get; set; } = DateTimeOffset.UtcNow;
    public DateTimeOffset? CompletedUtc { get; set; }
    public string? SourceIp { get; set; }
    public string? AuthenticatedUser { get; set; }

    /// <summary>
    /// Recipients (";"-delimited) that have already received a 250 on a previous attempt of this
    /// message. On retry the delivery skips them, so a multi-recipient/multi-domain message where one
    /// domain was temporarily down is never re-delivered to the recipients that already succeeded.
    /// </summary>
    public string? DeliveredRecipients { get; set; }

    /// <summary>
    /// Recipients (";"-delimited) that failed permanently (a 5xx) on an earlier attempt. They are final: a retry of
    /// the message skips them, and they are reported in the delivery status notification once the message ends.
    /// </summary>
    public string? FailedRecipients { get; set; }

    /// <summary>
    /// While <see cref="Status"/> is <see cref="MessageStatus.Delivering"/>: the moment the delivery claim expires.
    /// A row still Delivering after that (a worker that died between the send and its bookkeeping) is returned to
    /// the queue by the periodic lease sweep; its <see cref="DeliveredRecipients"/> keep a retry from re-sending.
    /// Null when the message is not being delivered.
    /// </summary>
    public DateTimeOffset? LeaseExpiresUtc { get; set; }

    /// <summary>Where the message came from; decides suppression and bounce (DSN) handling.</summary>
    public MessageOrigin Origin { get; set; } = MessageOrigin.Submitted;
}

public enum MessageStatus
{
    Queued = 0,
    Delivering = 1,
    Delivered = 2,
    Failed = 3,
    Bounced = 4,
    /// <summary>Not sent because every recipient is on the tenant's suppression list. Terminal — not retried.</summary>
    Suppressed = 5
}

/// <summary>Where a queued message came from.</summary>
public enum MessageOrigin
{
    /// <summary>Submitted by a client over SMTP or the pickup folder — ordinary relayed mail.</summary>
    Submitted = 0,

    /// <summary>
    /// Generated by the relay itself (reports, alerts, account mail). Exempt from the suppression list in both
    /// directions — a bounce never suppresses the report recipient — and never answered with a DSN.
    /// </summary>
    System = 1,

    /// <summary>A delivery status notification (bounce) generated by the relay. Sent with a null return path.</summary>
    DeliveryStatusNotification = 2
}

/// <summary>
/// A queued message without its body — what lists and the queue pick need. Loading <see cref="QueuedMessage.RawMessage"/>
/// for a list would read every message body in the queue.
/// </summary>
public sealed record QueuedMessageSummary(
    long Id,
    int TenantId,
    string MessageId,
    string Sender,
    string Recipients,
    int SizeBytes,
    MessageStatus Status,
    int RetryCount,
    string? LastError,
    DateTimeOffset CreatedUtc,
    DateTimeOffset NextRetryUtc,
    DateTimeOffset? CompletedUtc,
    string? DeliveredRecipients,
    string? FailedRecipients,
    MessageOrigin Origin);

/// <summary>A due message as the delivery scheduler sees it: enough to choose fairly, nothing more.</summary>
public sealed record QueueCandidate(long Id, int TenantId, string Recipients);

/// <summary>
/// The outcome of one delivery attempt, written in a single statement so the recipients that received the message
/// and the message status can never disagree (a crash between two writes re-sent mail).
/// </summary>
/// <param name="Status">The new status (Queued for a retry, or a terminal status).</param>
/// <param name="DeliveredRecipients">All recipients delivered so far (";"-delimited).</param>
/// <param name="FailedRecipients">All recipients that failed permanently so far (";"-delimited).</param>
/// <param name="RetryCount">The attempt counter after this attempt.</param>
/// <param name="NextRetryUtc">When a Queued message is next due.</param>
/// <param name="LastError">Summary of the last failure, null when there was none.</param>
public sealed record DeliveryAttemptOutcome(
    MessageStatus Status,
    string? DeliveredRecipients,
    string? FailedRecipients,
    int RetryCount,
    DateTimeOffset NextRetryUtc,
    string? LastError);
